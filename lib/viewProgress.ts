/*
 * GSAP(スクロール) → R3F(車両・カメラ・霧) をつなぐ橋渡し。
 *
 * 毎フレームReactのstateを更新すると、その都度コンポーネントツリーが再描画され
 * スクロール中に確実にコマ落ちする。そこでスクロール進行度は「モジュールスコープの
 * 可変オブジェクト」に書き込み、R3F側は useFrame の中から読むだけにする。
 * これによりReactの再レンダリングを一切発生させずに毎フレーム値を受け渡せる。
 *
 * 書き込み: GSAP ScrollTrigger の onUpdate / onEnter系（**ここ以外から書かない**）
 * 読み出し: useFrame(() => { ... viewProgress.page ... })
 *
 * ═══════════════════════════════════════════════════════════════
 *  車両アニメーションの設計原則（CEO指示・厳守）
 *
 *  1. Hero以外の車両アニメーションは、スクロール位置が唯一の駆動源。
 *     時間経過だけで進む値をここに持たせない。
 *  2. 逆スクロールで全ての値が正確に巻き戻ること。そのため各値は
 *     原則 progress(0→1) の**単調な関数**として書く。
 *  3. オブジェクトを差し替えず、必ず .x = ... のようにフィールド単位で書く。
 *     毎フレームのオブジェクト生成はGCプレッシャーになるため、
 *     ベクトル値も x/y/z を平坦なフィールドとして持つ。
 * ═══════════════════════════════════════════════════════════════
 */

export const viewProgress = {
  /** ページ全体の進行度 0→1。常設空間(Atmosphere)のカメラ前進量に対応する。 */
  page: 0,
  /** SCENE「視界が開く」の進行度 0→1。(Vision廃止に伴い現在は未使用) */
  vision: 0,
  /** Narrative(3D回廊)の進行度 0→1。(TOPから外したため現在は未使用) */
  corridor: 0,
  /** 直近のスクロール速度(正規化)。霧の流れと色収差の強さに使う。 */
  velocity: 0,

  /* ────────────────────────────────────────────────────────────
   * 車両リグ
   *
   * Hero完了時点の値が、そのままPhilosophy開始時の初期値になる。
   * 各セクションは前区間の終了値を引き継ぎ、1台のSUVが旅を続ける
   * ように連続する（禁止事項「車両をセクションごとに作り直さない」）。
   * ──────────────────────────────────────────────────────────── */

  /**
   * Hero完了〜Contact完了の全体進行度 0→1。
   * 個別区間の値を積算せず、ページ全体に対する絶対progressとして
   * 1箇所だけで書く。区間ごとに加算すると誤差が蓄積するため。
   */
  vehicleProgress: 0,

  /* 位置・姿勢（前セクションの終了値が次セクションの開始値。突然変更しない） */
  bodyX: 0,
  bodyY: 0,
  bodyZ: 0,
  /** 車体のY軸回転(ラジアン)。Philosophyでフロント3/4→側面→リアへ回す */
  bodyRotationY: 0,
  /**
   * サスペンションの沈み込み 0→1。
   * Hero終盤の停止時に一度だけ沈んで戻る。Hero区間は「サイト唯一の
   * 自動再生」なので、ここだけは時間ベースのtweenで書いてよい。
   */
  suspensionDip: 0,

  /* 可動部 */
  /** リアハッチ開閉 0(閉)→1(全開)。Philosophyで開き、Sellで閉じる */
  rearGateOpen: 0,
  /**
   * ホイールの回転角(ラジアン)。**累積量**だが、スクロール由来の値。
   *
   * GSAPからは「角速度」ではなく、この角度そのものを scrub で書く。
   * 角速度をuseFrame側で積分すると、スクロールを止めてもタイヤが
   * 回り続ける(=時間経過アニメーション)ことになり、CEO指示に反する。
   *
   * 逆スクロール時は角度が減る＝タイヤが逆回転するが、これは
   * 「車が後退している」という物理的に正しい表現なので破綻ではない。
   */
  wheelAngle: 0,

  /* ライト */
  /** ヘッドライト強度 0→1。Heroで点灯し、Contactで消灯 */
  headlightIntensity: 0,
  /** Philosophy: リアハッチが開いたとき荷室から漏れる光 0→1 */
  cargoLightIntensity: 0,

  /* 区間固有の演出（対応区間の外では値が保持されるだけ） */
  /** Sell: 車体を走査するスキャンラインの位置 0→1 */
  scanProgress: 0,
  /** Find: 分岐する光のラインの伸長 0→1 */
  routeLineProgress: 0,

  /* カメラ（useFrame側でlerp補間して追従する。突然移動させない） */
  cameraX: 0,
  cameraY: 1.6,
  cameraZ: 9,
  lookAtX: 0,
  lookAtY: 0.9,
  lookAtZ: 0,
};

export type ViewProgress = typeof viewProgress;

/** 現在アクティブな区間。演出のon/off判定に使う。 */
export type VehicleSection =
  | "hero"
  | "philosophy"
  | "sell"
  | "buy"
  | "find"
  | "contact";

/*
 * 区間名だけは値の性質が違う（連続量ではなく状態）ため別に持つ。
 * onEnter / onEnterBack / onLeave / onLeaveBack の**4つすべて**で
 * 書くこと。片方向だけだと逆スクロールで判定が壊れる。
 */
export const vehicleSection = {
  current: "hero" as VehicleSection,
};
