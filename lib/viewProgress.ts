/*
 * GSAP(スクロール) → R3F(カメラ・霧) をつなぐ橋渡し。
 *
 * 毎フレームReactのstateを更新すると、その都度コンポーネントツリーが再描画され
 * スクロール中に確実にコマ落ちする。そこでスクロール進行度は「モジュールスコープの
 * 可変オブジェクト」に書き込み、R3F側は useFrame の中から読むだけにする。
 * これによりReactの再レンダリングを一切発生させずに毎フレーム値を受け渡せる。
 *
 * 書き込み: GSAP ScrollTrigger の onUpdate / onEnter系（**ここ以外から書かない**）
 * 読み出し: useFrame(() => { ... viewProgress.page ... })
 *
 * 値はオブジェクトを差し替えず、必ずフィールド単位で書く。
 * 毎フレームのオブジェクト生成はGCプレッシャーになるため。
 */

export const viewProgress = {
  /** ページ全体の進行度 0→1。常設空間(Atmosphere)のカメラ前進量に対応する。 */
  page: 0,
  /** SCENE「視界が開く」の進行度 0→1。(Vision廃止に伴い現在は未使用) */
  vision: 0,
  /** Narrative(3D回廊)の進行度 0→1。(TOPから外したため現在は未使用) */
  corridor: 0,
  /** 直近のスクロール速度(正規化)。霧の流れと色収差の強さに使う。 */
  velocity: 0,

  /* ────────────────────────────────────────────────────────────
   * 車両リグ
   *
   * Hero完了時点の値が、そのままPhilosophy開始時の初期値になる。
   * 各セクションは前区間の終了値を引き継ぎ、1台のSUVが旅を続ける
   * ように連続する（禁止事項「車両をセクションごとに作り直さない」）。
   * ──────────────────────────────────────────────────────────── */

  /**
   * Hero完了〜Contact完了の全体進行度 0→1。
   * 個別区間の値を積算せず、ページ全体に対する絶対progressとして
   * 1箇所だけで書く。区間ごとに加算すると誤差が蓄積するため。
   */
};

export type ViewProgress = typeof viewProgress;

